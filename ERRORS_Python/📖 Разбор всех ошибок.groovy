 								Почему я сделал одну функцию get_name() вместо двух?

Потому что две твои функции (get_first_name и get_last_name) делают абсолютно одно и то же — отличаются только текстом в input().
Это классический случай дублирования кода.

									Правило хорошего программиста: 
Если две функции делают почти одинаковые вещи — их стоит объединить в одну универсальную, передав текст подсказки как параметр.

Это:
	Уменьшает объём кода
	Упрощает поддержку (если нужно изменить логику валидации — меняешь в одном месте)
	Делает код более профессиональным

Это один из самых важных принципов в программировании — DRY (Don't Repeat Yourself).

