### Разбор твоего кода:

```python
def greet_user(prompt: "Введите ваше имя") -> str:
```

**Это ошибка.**
`prompt: "Введите ваше имя"` — неправильно написан type hint.
Вместо строки ты должен указать **тип данных**. Правильно писать `prompt: str`.

---

```python
greet_user()
```

**Это тоже ошибка.**
Ты объявил функцию с параметром `prompt`, но вызываешь её **без аргумента**. Python выдаст ошибку.

---

### Правильная версия (с объяснениями):

```python
def greet_user(prompt: str) -> str:
    """Запрашивает имя у пользователя и возвращает его."""
    while True:
        name = input(prompt).strip()

        if not name:
            print("ERROR: Имя не может быть пустым.\n")
            continue

        return name


# Правильный вызов функции:
name = greet_user("Введите ваше имя: ")
print(f"Привет, {name}! Рад тебя видеть.")
```

---

### Важные моменты, которые нужно понять:

1. **Функция `greet_user()`** должна **только** возвращать имя. Она не должна сама печатать приветствие. Приветствие лучше выводить снаружи.
2. Type hint пишется как `prompt: str`, а не как текст подсказки.
3. Когда функция принимает параметр — его **обязательно** нужно передавать при вызове.

