    1. Зачем нужна строка .strip() после input()? Что будет, если её убрать?

 .strip() - позволяет обрезатьь пробелы у строки, тем самым гарантирует, то что введенное значение будет корректно валидироваться если пользователь введет только пробелы


    2. Что значит if not name:? Как это работает? Можно ли вместо этого написать if name == ""?

if not name - проверяет не пустой ли объект, то есть тут идет замена булева значения, для строки это будет работать так:
"" = False, not name = True. Можно, оба варианта сработают, но в официальной документации рекомендуется использовать if not name

    3. Почему return name должен быть внутри цикла while True, а не после него (с меньшим отступом)?
Согласно правилу: Все строки, которые находятся внутри while True, должны иметь одинаковый отступ (обычно 4 пробела). Иначе Python никогда не дойдёт до return, если цикл начал работать.


                                                                                Уточнения к твоим ответам:
.strip() — всё верно. Без него пользователь мог бы "обмануть" программу, введя только пробелы (" "). После .strip() такая строка превращается в "", и проверка if not name срабатывает.

if not name — хорошо.
Более точно: в Python пустая строка считается "ложью" (falsy). Поэтому if not name — это короткая и популярная запись для проверки "если строка пустая".
if name == "" тоже работает, но if not name считается более "питоническим".

return внутри цикла — правильно. Как только return срабатывает, функция немедленно завершается и возвращает значение. Поэтому цикл while True прерывается.


